"""受理边界：赛道与产品都明确不碰的两类问题。

1. 涉及个人的消息（个人信用、品行、隐私、家庭、财务）
2. 时政类话题

这里的判断只在**入口处**做一次，命中就整条拒答，不进入检索——
既避免误伤，也避免模型对不该回答的问题给出看似专业的结论。
"""
from __future__ import annotations

import re

# 个人隐私 / 品行 / 信用类：命中这些词，且不是在问企业，就拒答
_PRIVATE_WORDS = (
    "失信", "老赖", "被执行人", "违法", "犯罪", "判刑", "坐牢", "前科", "案底",
    "出轨", "离婚", "私生活", "绯闻", "包养", "小三",
    "身份证", "手机号", "住址", "户籍", "开房记录",
    "人品", "为人", "是不是好人",
)

# 这些词要看主语：说「我妈妈的病情」要拦，说「高血压的诊断标准」不能拦——
# 后者是公开的医学标准，拦掉就是误伤公共知识。
_SUBJECT_RE = re.compile(
    r"(我|你|他|她|某人|同事|朋友|老板|领导|邻居|亲戚|家人|父母|爸|妈|"
    r"儿子|女儿|孩子|老婆|老公|先生|女士|姓[\u4e00-\u9fa5]{1,2}的)"
)
_SUBJECT_ONLY_WORDS = (
    "病历", "病情", "诊断", "抑郁", "精神病", "体检报告",
    "工资", "收入", "存款", "房产", "负债", "欠钱",
)

# 出现这些，说明问的是组织而不是个人
_ORG_WORDS = (
    "公司", "企业", "集团", "分公司", "子公司", "银行", "学校", "大学", "医院",
    "研究院", "事务所", "门店", "工厂", "机构", "品牌", "平台", "协会", "基金",
)

# 明确的政治主体与事件。故意不收录「政策」「政府」这类通词——
# 「某市取消限行政策」属于可核实的公共事务，不应被拦。
_POLITICAL_WORDS = (
    "两会", "党代会", "人民代表大会", "政治协商", "政治局", "中央委员会",
    "外交部", "国防部", "国防", "军事", "战争", "开战", "军演",
    "选举", "公投", "示威", "游行", "抗议", "政变",
    "涉台", "涉港", "涉疆", "涉藏", "台独", "港独", "疆独", "藏独",
    "领导人", "国家主席", "国务院总理", "总书记", "省委书记", "市委书记",
    # 外国政坛同样属于时政，不能当普通事实去查（曾在实测中把
    # 「美国下一届总统是谁」判成「真 83」，这是漏拦造成的错误结论）
    "总统", "首相", "大选", "执政党", "议会", "弹劾", "内阁", "首脑",
)

_PERSON_HINT = re.compile(
    r"(这个人|那个人|某人|我同事|我老板|我朋友|我邻居|我亲戚|他是不是|她是不是|姓[\u4e00-\u9fa5]{1,2}的)"
)
_NAME_LIKE = re.compile(r"^[\u4e00-\u9fa5]{2,4}(是|叫|有没有|是不是)")


def check_personal(text: str) -> str:
    """是不是在问某个具体个人的私事。返回命中的词，空串表示不拦。"""
    body = text or ""
    if any(w in body for w in _ORG_WORDS):
        return ""                       # 问的是企业，放行
    hit = next((w for w in _PRIVATE_WORDS if w in body), "")
    if hit:
        return hit
    # 有主语才拦：避免把「诊断标准」「平均工资」这类公共知识误判成个人隐私
    if _SUBJECT_RE.search(body):
        return next((w for w in _SUBJECT_ONLY_WORDS if w in body), "")
    return ""


def check_political(text: str) -> str:
    body = text or ""
    return next((w for w in _POLITICAL_WORDS if w in body), "")


def check(text: str) -> tuple[str, str]:
    """返回 (类别, 命中的词)；类别为空表示可以受理。"""
    hit = check_personal(text)
    if hit:
        return "personal", hit
    hit = check_political(text)
    if hit:
        return "political", hit
    return "", ""
